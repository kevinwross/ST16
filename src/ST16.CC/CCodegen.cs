namespace ST16.CC;

/// <summary>
/// Code generator for the ST16 C core subset (plan P3.5/P4). Emits ST16
/// assembly with <c>; L&lt;line&gt;</c> markers (instruction → .c line) for
/// the .st16d post-process.
///
/// Calling convention (see implementation.md P3.5 design contract):
/// the caller stores each argument in the callee's frame slot
/// <c>calleeFrame − (p − i)</c> below the old SP (first argument slot 0,
/// last argument slot p−1); the callee's prologue only allocates its frame;
/// the result (if any) is returned on the top of the operand stack.
///
/// Frame layout (per function): slots 0..(params+locals−1) hold the
/// parameters and locals in declaration order; slots (params+locals)..
/// (params+locals+15) are the spill budget for deep expressions.
/// </summary>
public partial class CCodegen
{
    public const int SpWord = 0xE000;
    public const int GlobalsStart = 0xE001;
    public const int GlobalsEnd = 0xEFFF;
    public const int MaxDepth = 28;
    public const int SpillBudget = 16;

    private readonly CProgram _program;
    private readonly Dictionary<string, CSymbol> _functions;
    private readonly Dictionary<string, CSymbol> _globals;
    private readonly Dictionary<string, List<CSymbol>> _locals;

    private readonly List<string> _lines = new();
    private CStackManager _st = null!;

    // Data layout.
    private int _nextGlobal;
    private readonly Dictionary<string, int> _globalAddrs = new();
    private readonly List<(string Name, int Addr, byte[] Bytes)> _strings = new();
    private readonly Dictionary<CExpr, int> _stringAddr = new();

    // The software unsigned-divisor cells (see EmitUnsignedDivMod): the
    // ST16 DIV/MOD are signed-only, so unsigned division of values in
    // 0x8000..0xFFFF is computed with a subtraction loop that keeps the
    // running quotient and the divisor in these two scratch words.
    private int _scratchAddr;
    private int _scratchAddr2;

    // Per-function state.
    private int _bb;
    private string? _currentFunc;
    private int _localCount;
    private string? _breakLabel;
    private string? _contLabel;
    private readonly Stack<(string? Break, string? Cont)> _loops = new();

    public CCodegen(CProgram program, Dictionary<string, CSymbol> functions,
        Dictionary<string, CSymbol> globals, Dictionary<string, List<CSymbol>> locals)
    {
        _program = program;
        _functions = functions;
        _globals = globals;
        _locals = locals;
        // The stack manager is re-created per function (its spill-slot base
        // depends on the function's parameter + local counts).
        _st = new CStackManager(s => _lines.Add(s), SpillBudget, MaxDepth, 0);
    }

    /// <summary>Generates the complete assembly for the program.</summary>
    public string Generate()
    {
        ReserveData();

        foreach (var f in _program.Functions)
        {
            if (f.IsPrototype)
                continue; // no body to generate; a call to an undefined
                          // prototype fails at assembly with 'undefined symbol'
            GenerateFunction(f);
        }

        var text = new List<string>(4 + _lines.Count + 8 + _program.Globals.Count * 3 + _strings.Count * 4);
        text.Add("; generated by st16cc — do not edit");
        text.Add("; L1");
        text.Add("CALL main");
        text.Add("HALT");
        text.AddRange(_lines);

        // The SP word (initial frame base) and the global data region.
        text.Add($".org 0x{SpWord:X4}");
        text.Add("sp:");
        text.Add($".dw 0x{SpWord:X4}");
        text.Add($".org 0x{GlobalsStart:X4}");
        foreach (var g in _program.Globals)
            EmitGlobalData(text, g);
        foreach (var (name, addr, bytes) in _strings)
        {
            text.Add($".org 0x{addr:X4}");
            text.Add($"{name}:");
            foreach (var b in bytes)
                text.Add($".dw 0x{b:X2}");
            text.Add(".dw 0"); // NUL terminator
        }
        text.Add($".org 0x{_scratchAddr:X4}");
        text.Add("st16cc_scratch:");
        text.Add(".ds 2");
        return string.Join("\n", text) + "\n";
    }

    // ---------------------------------------------------------------------
    // Data reservation (globals, then string literals in first-use order)
    // ---------------------------------------------------------------------

    private void ReserveData()
    {
        _nextGlobal = GlobalsStart;
        foreach (var g in _program.Globals)
        {
            _globalAddrs[g.Name] = _nextGlobal;
            _nextGlobal += g.Type.Kind == CTypeKind.Array ? g.Type.ArrayLen : 1;
        }

        // A char array initialized by a string inlines the bytes; a pointer
        // global initialized by a string needs the string data itself.
        foreach (var g in _program.Globals)
            if (g.Type.Kind != CTypeKind.Array && g.Init is CLit { Kind: CLitKind.String } lit)
                ReserveString(lit);

        foreach (var f in _program.Functions)
            WalkForStrings(f.Body);

        // Two reserved words for the unsigned-division scratch cells.
        _scratchAddr = _nextGlobal;      // running quotient
        _scratchAddr2 = _nextGlobal + 1; // divisor (kept while the loop compares)
        _nextGlobal += 2;

        if (_nextGlobal > GlobalsEnd + 1)
            throw new CCException(new CCDiagnostic(0, 0,
                $"global data (globals and string literals) exceeds the 0xE001…0xEFFF region; the ST16 profile supports {GlobalsEnd - GlobalsStart + 1} words of global data"));
    }

    private void ReserveString(CLit lit)
    {
        if (_stringAddr.ContainsKey(lit))
            return;
        string name = $"str{_strings.Count}";
        int addr = _nextGlobal;
        _nextGlobal += lit.Bytes!.Length + 1; // + NUL terminator
        _strings.Add((name, addr, lit.Bytes));
        _stringAddr[lit] = addr;
    }

    private void WalkForStrings(CStmt s)
    {
        switch (s)
        {
            case CBlock b:
                foreach (var st in b.Statements)
                    WalkForStrings(st);
                break;
            case CDecl d:
                foreach (var v in d.Vars)
                    if (v.Init is not null)
                        WalkForStringsExpr(v.Init);
                break;
            case CIf c:
                WalkForStringsExpr(c.Cond);
                WalkForStrings(c.Then);
                if (c.Else is not null)
                    WalkForStrings(c.Else);
                break;
            case CWhile w:
                WalkForStringsExpr(w.Cond);
                WalkForStrings(w.Body);
                break;
            case CDoWhile dw:
                WalkForStrings(dw.Body);
                WalkForStringsExpr(dw.Cond);
                break;
            case CFor fo:
                if (fo.Init is CDecl di)
                    foreach (var v in di.Vars)
                        if (v.Init is not null)
                            WalkForStringsExpr(v.Init);
                else if (fo.Init is CExprStmt es)
                    WalkForStringsExpr(es.Expr);
                if (fo.Cond is not null)
                    WalkForStringsExpr(fo.Cond);
                WalkForStrings(fo.Body);
                if (fo.Step is not null)
                    WalkForStringsExpr(fo.Step);
                break;
            case CLabel l:
                WalkForStrings(l.Target);
                break;
            case CReturn r:
                if (r.Value is not null)
                    WalkForStringsExpr(r.Value);
                break;
            case CExprStmt es:
                WalkForStringsExpr(es.Expr);
                break;
        }
    }

    private void WalkForStringsExpr(CExpr e)
    {
        switch (e)
        {
            case CLit lit when lit.Kind == CLitKind.String:
                ReserveString(lit);
                break;
            case CIndex ix:
                WalkForStringsExpr(ix.Base);
                WalkForStringsExpr(ix.Index);
                break;
            case CUnary u:
                WalkForStringsExpr(u.Operand);
                break;
            case CPostfix p:
                WalkForStringsExpr(p.Operand);
                break;
            case CBinary b:
                // Mirrors the codegen evaluation order (assignment: RHS first).
                if (b.Op == BOp.Assign)
                {
                    WalkForStringsExpr(b.Right);
                    WalkForStringsExpr(b.Left);
                }
                else
                {
                    WalkForStringsExpr(b.Left);
                    WalkForStringsExpr(b.Right);
                }
                break;
            case CTernary t:
                WalkForStringsExpr(t.Cond);
                WalkForStringsExpr(t.Then);
                WalkForStringsExpr(t.Else);
                break;
            case CCall c:
                foreach (var a in c.Args)
                    WalkForStringsExpr(a);
                break;
            case CSizeof so:
                if (so.Expr is not null)
                    WalkForStringsExpr(so.Expr);
                break;
            case CArrayInit ai:
                foreach (var it in ai.Items)
                    WalkForStringsExpr(it);
                break;
        }
    }

    // ---------------------------------------------------------------------
    // Functions
    // ---------------------------------------------------------------------

    private void GenerateFunction(CFuncDef f)
    {
        _currentFunc = f.Name;
        _localCount = _locals[f.Name].Count;
        // Spill slots follow the parameters and locals (slot p+l+k =
        // _localCount + k), so the whole frame (_localCount + spill
        // budget) is what the prologue reserves.
        _st = new CStackManager(s => _lines.Add(s), SpillBudget, MaxDepth,
            _localCount);
        _st.Reset();
        _breakLabel = null;
        _contLabel = null;

        // _localCount is params + locals (the semantics phase numbers
        // slots 0..p−1 for parameters, then locals), so the full frame is
        // params + locals + spill budget: the caller stores argument i at
        // old-SP − (frame − i) = the callee's slot i, and spill slots
        // p+l..p+l+s−1 stay inside the frame (never touching the caller's
        // frame).
        int frame = _localCount + SpillBudget;

        EmitLabel(f.Name);
        Mark(f.Line);

        // Prologue: SP ← [SP] − frame. (Arguments already sit in slots
        // 0..p−1, stored by the caller.)
        _st.Push($"PUSH16 0x{SpWord:X4}");
        _st.Load();
        _st.Push($"PUSH {frame}");
        _st.Op("SUB");
        _st.Push($"PUSH16 0x{SpWord:X4}");
        _st.Store();

        // Local initializers are materialized by the CDecl statements in the
        // body (in source order); nothing to do here.
        EmitStmt(f.Body);

        // A function whose body ends in 'return' needs no trailing epilogue.
        if (!EndsWithReturn(f.Body))
            EmitEpilogue(frame);
    }

    private void EmitEpilogue(int frame)
    {
        // SP ← [SP] + frame; RET. A return value (if any) stays on the
        // operand stack through the sequence.
        _lines.Add($"PUSH16 0x{SpWord:X4}");
        _lines.Add("LOAD");
        _lines.Add($"PUSH {frame}");
        _lines.Add("ADD");
        _lines.Add($"PUSH16 0x{SpWord:X4}");
        _lines.Add("STORE");
        _lines.Add("RET");
    }

    // ---------------------------------------------------------------------
    // Statements
    // ---------------------------------------------------------------------

    private void EmitStmt(CStmt s)
    {
        switch (s)
        {
            case CBlock b:
                foreach (var st in b.Statements)
                    EmitStmt(st);
                break;

            case CDecl d:
                foreach (var v in d.Vars)
                {
                    if (v.Init is null)
                        continue;
                    Mark(d.Line);
                    if (v.Type.Kind == CTypeKind.Array)
                        EmitArrayInit(v, d.Line);
                    else
                    {
                        Emit(v.Init);
                        CharMaskIf(v.Type);
                        StoreIntoSlot(SlotOf(v.Name));
                    }
                }
                break;

            case CIf c:
            {
                Mark(c.Line);
                Emit(c.Cond);
                string end = NewLabel();
                if (c.Else is not null)
                {
                    string els = NewLabel();
                    _st.JZ(els);
                    EmitStmt(c.Then);
                    _lines.Add($"JMP {end}");
                    EmitLabel(els);
                    EmitStmt(c.Else);
                    EmitLabel(end);
                }
                else
                {
                    _st.JZ(end);
                    EmitStmt(c.Then);
                    EmitLabel(end);
                }
                break;
            }

            case CWhile w:
            {
                string start = NewLabel();
                string end = NewLabel();
                EmitLabel(start);
                Mark(w.Line);
                Emit(w.Cond);
                _st.JZ(end);
                PushLoop(end, start);
                EmitStmt(w.Body);
                PopLoop();
                _lines.Add($"JMP {start}");
                EmitLabel(end);
                break;
            }

            case CDoWhile dw:
            {
                // break/continue fall through (the condition follows the body).
                string start = NewLabel();
                EmitLabel(start);
                PushLoop(null, null);
                EmitStmt(dw.Body);
                PopLoop();
                Mark(dw.Line);
                Emit(dw.Cond);
                _st.JNZ(start);
                break;
            }

            case CFor fo:
            {
                if (fo.Init is CDecl di)
                    EmitStmt(di);
                else if (fo.Init is CExprStmt es)
                {
                    Mark(es.Line);
                    Emit(es.Expr);
                    _st.Drop();
                }

                string start = NewLabel();
                string step = NewLabel();
                string end = NewLabel();
                EmitLabel(start);
                if (fo.Cond is not null)
                {
                    Mark(fo.Line);
                    Emit(fo.Cond);
                    _st.JZ(end);
                }
                PushLoop(end, step);
                EmitStmt(fo.Body);
                PopLoop();
                EmitLabel(step);
                if (fo.Step is not null)
                {
                    Mark(fo.Line);
                    Emit(fo.Step);
                    _st.Drop();
                }
                _lines.Add($"JMP {start}");
                EmitLabel(end);
                break;
            }

            case CBreak:
                if (_breakLabel is not null)
                {
                    Mark(s.Line);
                    _lines.Add($"JMP {_breakLabel}");
                }
                break;

            case CContinue:
                if (_contLabel is not null)
                {
                    Mark(s.Line);
                    _lines.Add($"JMP {_contLabel}");
                }
                break;

            case CGoto g:
                Mark(s.Line);
                _lines.Add($"JMP {g.Label}");
                break;

            case CLabel l:
                EmitLabel(l.Name);
                EmitStmt(l.Target);
                break;

            case CReturn r:
                if (r.Value is not null)
                {
                    Mark(s.Line);
                    Emit(r.Value);
                }
                EmitEpilogue(_localCount + SpillBudget);
                break;

            case CExprStmt es:
                Mark(es.Line);
                Emit(es.Expr);
                _st.Drop();
                break;
        }
    }

    private void PushLoop(string? breakTarget, string? contTarget)
    {
        _loops.Push((_breakLabel, _contLabel));
        _breakLabel = breakTarget;
        _contLabel = contTarget;
    }

    private void PopLoop()
    {
        var (b, c) = _loops.Pop();
        _breakLabel = b;
        _contLabel = c;
    }

    // ---------------------------------------------------------------------
    // Frame access idioms
    // ---------------------------------------------------------------------

    /// <summary>(value on top) → stored in the local slot; the value is consumed.</summary>
    private void StoreIntoSlot(int slot)
    {
        _st.Push($"PUSH16 0x{SpWord:X4}");
        _st.Load();
        _st.Push($"PUSH {slot}");
        _st.Op("ADD");
        _st.Store();
    }

    /// <summary>Loads a local/param slot, leaving the value on top.</summary>
    private void LoadFromSlot(int slot, CType type)
    {
        _st.Push($"PUSH16 0x{SpWord:X4}");
        _st.Load();
        _st.Push($"PUSH {slot}");
        _st.Op("ADD");
        _st.Load();
        AdjustCharLoad(type);
    }

    /// <summary>Leaves the address of a local/param slot on top.</summary>
    private void AddressOfSlot(int slot)
    {
        _st.Push($"PUSH16 0x{SpWord:X4}");
        _st.Load();
        _st.Push($"PUSH {slot}");
        _st.Op("ADD");
    }

    /// <summary>
    /// Adjust a freshly loaded char to its C value: signed chars are
    /// sign-extended (<c>(x &lt;&lt; 8) &gt;&gt; 8</c>); unsigned chars are
    /// masked to the low byte.
    /// </summary>
    private void AdjustCharLoad(CType t)
    {
        if (t.Kind != CTypeKind.Scalar || t.Base != CBaseKind.Char)
            return;
        if (t.Unsigned)
        {
            _st.Push("PUSH16 0x00FF");
            _st.Op("AND");
        }
        else
        {
            // SLL/SLR (spec §5.2): value on top, count second → the count is
            // pushed, then the value is brought back on top with SWAP.
            _st.Push("PUSH 8");
            _st.Swap();
            _st.Op("SLL");
            _st.Push("PUSH 8");
            _st.Swap();
            _st.Op("SLR");
        }
    }

    /// <summary>Truncate a value to the char byte before storing.</summary>
    private void CharMaskIf(CType t)
    {
        if (t.Kind != CTypeKind.Scalar || t.Base != CBaseKind.Char)
            return;
        _st.Push("PUSH16 0x00FF");
        _st.Op("AND");
    }

    /// <summary>Initializes an array local (element by element).</summary>
    private void EmitArrayInit(CVarDecl v, int line)
    {
        int n = v.Type.ArrayLen;
        byte[]? strBytes = v.Init is CLit { Kind: CLitKind.String } sl ? sl.Bytes : null;
        CArrayInit? items = v.Init as CArrayInit;

        for (int i = 0; i < n; i++)
        {
            if (strBytes is not null && i < strBytes.Length)
            {
                PushIntScalar(strBytes[i]);
            }
            else if (items is not null && i < items.Items.Count)
            {
                var item = items.Items[i];
                if (item is CLit lit)
                    PushIntScalar(lit.Value);
                else
                    Emit(item);
            }
            else
            {
                PushIntScalar(0);
            }
            CharMaskIf(v.Type.Element!);
            StoreIntoSlot(SlotOf(v.Name) + i);
        }
    }

    // ---------------------------------------------------------------------
    // Symbols, labels, helpers
    // ---------------------------------------------------------------------

    private CSymbol? FindLocal(string name)
    {
        foreach (var l in _locals[_currentFunc!])
            if (l.Name == name)
                return l;
        return null;
    }

    private int SlotOf(string name) => FindLocal(name)!.Slot;

    private static (CDecl? Decl, CVarDecl? Var) FindLocalDecl(CFuncDef f, string name)
    {
        (CDecl? Decl, CVarDecl? Var) Search(CStmt s)
        {
            switch (s)
            {
                case CBlock b:
                    foreach (var st in b.Statements)
                    {
                        var r = Search(st);
                        if (r.Decl is not null)
                            return r;
                    }
                    return (null, null);
                case CDecl d:
                    foreach (var v in d.Vars)
                        if (v.Name == name)
                            return (d, v);
                    return (null, null);
                case CFor fo:
                    if (fo.Init is CDecl di)
                        foreach (var v in di.Vars)
                            if (v.Name == name)
                                return (di, v);
                    return Search(fo.Body);
                case CLabel l:
                    return Search(l.Target);
                default:
                    return (null, null);
            }
        }

        return Search(f.Body);
    }

    private static bool EndsWithReturn(CBlock body)
    {
        for (int i = body.Statements.Count - 1; i >= 0; i--)
        {
            var s = body.Statements[i];
            if (s is CLabel l)
            {
                s = l.Target;
                continue;
            }
            if (s is CDecl)
                continue;
            return s is CReturn;
        }
        return false;
    }

    private string NewLabel() => $"bb{_bb++}";

    private void EmitLabel(string name) => _lines.Add($"{name}:");

    private void Mark(int line) => _lines.Add($"; L{line}");

    private void EmitGlobalData(List<string> text, CGlobalVar g)
    {
        text.Add($"{g.Name}:");
        if (g.Type.Kind == CTypeKind.Array)
        {
            int n = g.Type.ArrayLen;
            byte[]? sb = g.Init is CLit { Kind: CLitKind.String } sl ? sl.Bytes : null;
            CArrayInit? ai = g.Init as CArrayInit;
            CLit? single = (g.Init is CLit cl && cl.Kind != CLitKind.String) ? cl : null;
            for (int i = 0; i < n; i++)
            {
                long val;
                if (sb is not null && i < sb.Length)
                    val = sb[i];
                else if (ai is not null && i < ai.Items.Count && ai.Items[i] is CLit il)
                    val = il.Value;
                else if (single is not null && i == 0)
                    val = single.Value;
                else
                    val = 0;
                text.Add($".dw 0x{((int)(val & 0xFFFF)):X4}");
            }
            return;
        }

        if (g.Init is CLit lit)
        {
            if (lit.Kind == CLitKind.String)
                text.Add($".dw 0x{_stringAddr[lit]:X4}");
            else
                text.Add($".dw 0x{((int)(lit.Value & 0xFFFF)):X4}");
        }
        else
        {
            text.Add(".ds 1");
        }
    }
}
